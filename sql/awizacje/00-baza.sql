  using ((select public.moja_rola()) = 'logistyka'
         or ((select public.moja_rola()) = 'przewoznik' and firma_id = (select public.moja_firma())));
create policy awizacje_dodawanie on public.awizacje for insert to authenticated
  with check ((select public.moja_rola()) = 'logistyka'
              or ((select public.moja_rola()) = 'przewoznik' and firma_id = (select public.moja_firma())));
create policy awizacje_zmiana on public.awizacje for update to authenticated
  using ((select public.moja_rola()) = 'logistyka'
         or ((select public.moja_rola()) = 'przewoznik' and firma_id = (select public.moja_firma())))
  with check ((select public.moja_rola()) = 'logistyka'
              or ((select public.moja_rola()) = 'przewoznik' and firma_id = (select public.moja_firma())));


