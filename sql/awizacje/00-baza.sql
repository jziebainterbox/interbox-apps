-- firmy
drop policy if exists firmy_odczyt    on public.firmy;
drop policy if exists firmy_dodawanie on public.firmy;
drop policy if exists firmy_zmiana    on public.firmy;
create policy firmy_odczyt on public.firmy for select to authenticated
  using ((select public.moja_rola()) = 'logistyka' or id = (select public.moja_firma()));
create policy firmy_dodawanie on public.firmy for insert to authenticated
  with check ((select public.moja_rola()) = 'logistyka');
create policy firmy_zmiana on public.firmy for update to authenticated
  using ((select public.moja_rola()) = 'logistyka')
  with check ((select public.moja_rola()) = 'logistyka');

-- profile (konta)
drop policy if exists profile_odczyt on public.profile;
drop policy if exists profile_zmiana on public.profile;
create policy profile_odczyt on public.profile for select to authenticated
  using (id = auth.uid() or (select public.moja_rola()) = 'logistyka');
create policy profile_zmiana on public.profile for update to authenticated
  using ((select public.moja_rola()) = 'logistyka')
  with check ((select public.moja_rola()) = 'logistyka');

-- konta oczekujące
drop policy if exists oczekujace_logistyka on public.konta_oczekujace;
create policy oczekujace_logistyka on public.konta_oczekujace for all to authenticated
  using ((select public.moja_rola()) = 'logistyka')
  with check ((select public.moja_rola()) = 'logistyka');

-- rampy
drop policy if exists rampy_odczyt    on public.rampy;
drop policy if exists rampy_dodawanie on public.rampy;
drop policy if exists rampy_zmiana    on public.rampy;
create policy rampy_odczyt on public.rampy for select to authenticated
  using ((select public.moja_rola()) is not null);
create policy rampy_dodawanie on public.rampy for insert to authenticated
  with check ((select public.moja_rola()) = 'logistyka');
create policy rampy_zmiana on public.rampy for update to authenticated
  using ((select public.moja_rola()) = 'logistyka')
  with check ((select public.moja_rola()) = 'logistyka');

-- ustawienia
drop policy if exists ustawienia_odczyt on public.ustawienia;
drop policy if exists ustawienia_zmiana on public.ustawienia;
create policy ustawienia_odczyt on public.ustawienia for select to authenticated
  using ((select public.moja_rola()) is not null);
create policy ustawienia_zmiana on public.ustawienia for update to authenticated
  using ((select public.moja_rola()) = 'logistyka')
  with check ((select public.moja_rola()) = 'logistyka');

-- zajętość: widzi każdy zalogowany (same godziny, bez danych)
drop policy if exists zajetosc_odczyt on public.zajetosc;
create policy zajetosc_odczyt on public.zajetosc for select to authenticated
  using ((select public.moja_rola()) is not null);

-- awizacje: logistyka wszystko, przewoźnik tylko swojej firmy; nikt nie kasuje (jest odwołanie)
drop policy if exists awizacje_odczyt    on public.awizacje;
drop policy if exists awizacje_dodawanie on public.awizacje;
drop policy if exists awizacje_zmiana    on public.awizacje;
