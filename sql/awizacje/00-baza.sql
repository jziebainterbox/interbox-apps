-- 4. Funkcje pomocnicze ------------------------------------------------
create or replace function public.awz_hhmm(m int) returns text
language sql immutable as $$
  select lpad((m / 60)::text, 2, '0') || ':' || lpad((m % 60)::text, 2, '0')
$$;

-- rola zalogowanego: 'logistyka' / 'przewoznik' / null (brak konta, konto lub firma zablokowane)
create or replace function public.moja_rola() returns text
language sql stable security definer set search_path = public as $$
  select p.rola
  from public.profile p
  left join public.firmy f on f.id = p.firma_id
  where p.id = auth.uid()
    and p.aktywny
    and (p.rola = 'logistyka' or coalesce(f.aktywna, false))
$$;

create or replace function public.moja_firma() returns bigint
language sql stable security definer set search_path = public as $$
  select p.firma_id from public.profile p where p.id = auth.uid() and p.aktywny
$$;


-- 5. Nowe konta: tylko przygotowane przez logistykę ---------------------
create or replace function public.awizacja_nowe_konto() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  k public.konta_oczekujace%rowtype;
begin
  select * into k
  from public.konta_oczekujace
  where lower(email) = lower(new.email) and wygasa > now();

  if not found then
    raise exception 'Konto % nie zostało przygotowane w programie Awizacja.', new.email;
  end if;

  insert into public.profile (id, login, imie, rola, firma_id)
  values (new.id, lower(k.login), k.imie, k.rola, k.firma_id);

  delete from public.konta_oczekujace where email = k.email;
  return new;
end $$;

drop trigger if exists awizacja_nowe_konto on auth.users;
create trigger awizacja_nowe_konto
  after insert on auth.users
  for each row execute function public.awizacja_nowe_konto();

