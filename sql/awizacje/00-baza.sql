-- =====================================================================
--  AWIZACJA v1 — baza danych (Supabase / PostgreSQL)
--
--  Jak użyć: Supabase → SQL Editor → New query → wklej CAŁY plik → Run.
--  Plik można uruchomić ponownie — nie kasuje danych.
--
--  Co tu jest:
--    firmy             – przewoźnicy / klienci
--    profile           – konta programu (login, rola, firma)
--    konta_oczekujace  – konta przygotowane przez logistykę, czekające na utworzenie
--    rampy             – rampy (na start jedna: R1)
--    ustawienia        – godziny pracy, długość okna, limity, dni wolne
--    awizacje          – rezerwacje okien (pełne dane)
--    zajetosc          – same godziny zajętych okien (bez danych firm i kierowców),
--                        żeby przewoźnik widział, co zajęte, ale nie u kogo
--
--  Zasady pilnowane w bazie (nie da się ich obejść z przeglądarki):
--    * jedno okno na rampie = jedna aktywna awizacja (blokada nakładania się),
--    * przewoźnik widzi i zmienia tylko awizacje swojej firmy,
--    * przewoźnik rezerwuje tylko w godzinach pracy, w granicach okien i limitów,
--    * konto może powstać tylko wtedy, gdy logistyka przygotowała je w programie.
-- =====================================================================


-- 1. Rozszerzenia ------------------------------------------------------
create extension if not exists btree_gist with schema extensions;
create extension if not exists pgcrypto  with schema extensions;


-- 2. Tabele ------------------------------------------------------------
create table if not exists public.firmy (
  id         bigint generated by default as identity primary key,
  nazwa      text not null,
  nip        text,
  telefon    text,
  email      text,
  uwagi      text,
  aktywna    boolean not null default true,
  utworzono  timestamptz not null default now()
);

create table if not exists public.profile (
  id         uuid primary key references auth.users (id) on delete cascade,
  login      text not null unique check (login = lower(login)),
  imie       text,
  rola       text not null check (rola in ('logistyka', 'przewoznik')),
  firma_id   bigint references public.firmy (id),
  aktywny    boolean not null default true,
  utworzono  timestamptz not null default now(),
  constraint profil_firma check (rola = 'logistyka' or firma_id is not null)
);

create table if not exists public.konta_oczekujace (
  email      text primary key,
  login      text not null,
  imie       text,
  rola       text not null check (rola in ('logistyka', 'przewoznik')),
  firma_id   bigint references public.firmy (id),
  wygasa     timestamptz not null default now() + interval '1 day'
);

create table if not exists public.rampy (
  id         int generated by default as identity primary key,
  kod        text not null unique,
  nazwa      text not null,
  kolejnosc  int not null default 1,
  aktywna    boolean not null default true
);

create table if not exists public.ustawienia (
  id               int primary key default 1 check (id = 1),
  okno_min         int not null default 30   check (okno_min in (15, 20, 30, 60)),
  od_min           int not null default 360,           -- 06:00 (minuty od północy)
  do_min           int not null default 1320,          -- 22:00
  dni_robocze      int[]  not null default '{1,2,3,4,5}', -- 1 = poniedziałek … 7 = niedziela
  dni_wolne        date[] not null default '{}',
  dni_naprzod      int not null default 14,            -- rezerwacja najwyżej tyle dni naprzód
  min_wyprzedzenie int not null default 60,            -- rezerwacja najpóźniej tyle minut przed oknem
  odwolanie_min    int not null default 120,           -- zmiana / odwołanie najpóźniej tyle minut przed oknem
  max_okien        int not null default 4,             -- jedna rezerwacja = najwyżej tyle okien
  strefa           text not null default 'Europe/Warsaw',
  constraint ustawienia_godziny check (od_min >= 0 and do_min <= 1440 and od_min < do_min)
);

create table if not exists public.awizacje (
  id               bigint generated by default as identity primary key,
  rampa_id         int not null references public.rampy (id),
  poczatek         timestamptz not null,
  koniec           timestamptz not null,
  rodzaj           text not null check (rodzaj in ('dostawa', 'odbior')),
  firma_id         bigint not null references public.firmy (id),
  nr_rej           text not null,
  kierowca         text,
  telefon          text,
  palety           int check (palety is null or palety between 0 and 200),
  nr_dokumentu     text,
  uwagi            text,
  status           text not null default 'aktywna' check (status in ('aktywna', 'odwolana')),
  powod_odwolania  text,
  utworzyl         uuid default auth.uid(),
  utworzono        timestamptz not null default now(),
  zmienil          uuid,
  zmieniono        timestamptz,
  odwolal          uuid,
  odwolano         timestamptz,
  constraint awizacja_czas check (koniec > poczatek),
  constraint awizacja_bez_nakladania exclude using gist (
    rampa_id with =,
    tstzrange(poczatek, koniec, '[)') with &&
  ) where (status = 'aktywna')
);
create index if not exists awizacje_poczatek on public.awizacje (poczatek);
create index if not exists awizacje_firma    on public.awizacje (firma_id, poczatek);

create table if not exists public.zajetosc (
  id        bigint primary key references public.awizacje (id) on delete cascade,
  rampa_id  int not null,
  poczatek  timestamptz not null,
  koniec    timestamptz not null
);
create index if not exists zajetosc_poczatek on public.zajetosc (poczatek);


