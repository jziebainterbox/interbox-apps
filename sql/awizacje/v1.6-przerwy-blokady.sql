-- =====================================================================
--  AWIZACJA v1.6 — przerwy i ręczne blokowanie okien
--  Supabase → SQL Editor → New query → wklej CAŁY plik → Run.
--  Można uruchomić ponownie — nic nie kasuje.
--
--  Co robi:
--    * nowa tabela „blokady”:
--        przerwa = stała, co tydzień w wybrane dni (np. 12:00–12:30 pn–pt),
--        blokada = jednorazowa, w konkretnym dniu (np. 14.11 10:00–12:00),
--    * dodaje je i usuwa każde konto biura (logistyka),
--      przewoźnik tylko widzi, że czas jest niedostępny,
--    * w tym czasie nikt nie wpisze ani nie przesunie awizacji (także biuro),
--    * awizacje wpisane wcześniej w tym czasie zostają (można je odwołać).
-- =====================================================================

create table if not exists public.blokady (
  id         bigint generated by default as identity primary key,
  rodzaj     text not null check (rodzaj in ('przerwa', 'blokada')),
  rampa_id   int references public.rampy (id),          -- null = wszystkie rampy
  dzien      date,                                       -- tylko blokada
  dni        int[] not null default '{1,2,3,4,5,6,7}',   -- tylko przerwa (1 = pn … 7 = nd)
  od_min     int not null check (od_min between 0 and 1439),
  do_min     int not null check (do_min between 1 and 1440),
  opis       text,
  utworzyl   uuid default auth.uid(),
  utworzono  timestamptz not null default now(),
  check (od_min < do_min),
  check (rodzaj = 'przerwa' or dzien is not null)
);

alter table public.blokady enable row level security;

drop policy if exists blokady_odczyt    on public.blokady;
drop policy if exists blokady_dodawanie on public.blokady;
drop policy if exists blokady_zmiana    on public.blokady;
drop policy if exists blokady_usuwanie  on public.blokady;
create policy blokady_odczyt on public.blokady for select to authenticated
  using ((select public.moja_rola()) is not null);
create policy blokady_dodawanie on public.blokady for insert to authenticated
  with check ((select public.moja_rola()) = 'logistyka');
create policy blokady_zmiana on public.blokady for update to authenticated
  using ((select public.moja_rola()) = 'logistyka')
  with check ((select public.moja_rola()) = 'logistyka');
create policy blokady_usuwanie on public.blokady for delete to authenticated
  using ((select public.moja_rola()) = 'logistyka');

grant select, insert, update, delete on public.blokady to authenticated;

-- zmiany przerw i blokad widać u innych od razu
do $$
begin
  if exists (select 1 from pg_publication where pubname = 'supabase_realtime')
     and not exists (select 1 from pg_publication_tables
                     where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'blokady') then
    alter publication supabase_realtime add table public.blokady;
  end if;
end $$;


-- czy czas awizacji nachodzi na przerwę / blokadę? zwraca komunikat albo null
create or replace function public.awz_kolizja_blokady(p_rampa int, p_od timestamptz, p_do timestamptz)
returns text
language plpgsql stable security definer set search_path = public as $$
declare
  strefa text := coalesce((select u.strefa from public.ustawienia u where u.id = 1), 'Europe/Warsaw');
  lp  timestamp := p_od at time zone strefa;
  m0  int := extract(hour from lp)::int * 60 + extract(minute from lp)::int;
  m1  int := round(extract(epoch from ((p_do at time zone strefa) - date_trunc('day', lp))) / 60)::int;
  b   public.blokady%rowtype;
begin
  select * into b from public.blokady x
   where (x.rampa_id is null or x.rampa_id = p_rampa)
     and x.od_min < m1 and x.do_min > m0
     and ((x.rodzaj = 'blokada' and x.dzien = lp::date)
       or (x.rodzaj = 'przerwa' and extract(isodow from lp)::int = any (x.dni)))
   order by x.od_min
   limit 1;
  if not found then
    return null;
  end if;
  return (case when b.rodzaj = 'przerwa' then 'W tym czasie jest przerwa' else 'Ten czas jest zablokowany' end)
      || ' (' || public.awz_hhmm(b.od_min) || '–' || public.awz_hhmm(b.do_min)
      || coalesce(' · ' || nullif(trim(b.opis), ''), '') || ') – wybierz inną godzinę.';
end $$;


-- strażnik awizacji: + sprawdzanie przerw i blokad
create or replace function public.awizacje_przed_zapisem() returns trigger
language plpgsql security definer set search_path = public as $$
declare
  u     public.ustawienia%rowtype;
  rola  text := public.moja_rola();
  lp    timestamp;
  lk    timestamp;
  m0    int;
  m1    int;
  czas_zmieniony boolean;
  opis_bl text;
begin
  -- zapis z panelu Supabase / SQL Editora (bez zalogowanego użytkownika) = administrator
  if rola is null and (coalesce(auth.role(), '') = 'service_role' or session_user <> 'authenticator') then
    rola := 'admin';
  end if;
  if rola is null then
    raise exception 'Brak uprawnień – konto albo firma jest zablokowana.';
  end if;

  select * into u from public.ustawienia where id = 1;

  if tg_op = 'INSERT' then
    new.utworzyl := auth.uid();
    new.utworzono := now();
    new.status := 'aktywna';
    new.zmienil := null;  new.zmieniono := null;
    new.odwolal := null;  new.odwolano := null;  new.powod_odwolania := null;
  else
    new.id := old.id;
    new.utworzyl := old.utworzyl;
    new.utworzono := old.utworzono;
    new.zmienil := auth.uid();
    new.zmieniono := now();
  end if;

  new.nr_rej := upper(regexp_replace(trim(coalesce(new.nr_rej, '')), '\s+', ' ', 'g'));
  if new.nr_rej = '' then
    raise exception 'Podaj numer rejestracyjny.';
  end if;

  if rola = 'przewoznik' then
    new.firma_id := public.moja_firma();
    if tg_op = 'UPDATE' then
      if old.status <> 'aktywna' then
        raise exception 'Ta awizacja jest już odwołana.';
      end if;
      if old.poczatek < now() + make_interval(mins => u.odwolanie_min) then
        raise exception 'Zmiana lub odwołanie jest możliwe najpóźniej % min przed oknem. Zadzwoń do logistyki.', u.odwolanie_min;
      end if;
    end if;
  end if;

  -- odwołanie: zapamiętaj kto i kiedy, godzin już nie zmieniamy
  if new.status = 'odwolana' then
    if tg_op = 'UPDATE' then
      new.poczatek := old.poczatek;
      new.koniec := old.koniec;
      new.rampa_id := old.rampa_id;
      if old.status = 'aktywna' then
        new.odwolal := auth.uid();
        new.odwolano := now();
      else
        new.odwolal := old.odwolal;
        new.odwolano := old.odwolano;
      end if;
    else
      new.odwolal := auth.uid();
      new.odwolano := now();
    end if;
    return new;
  end if;

  -- przywrócenie odwołanej (tylko logistyka – przewoźnik odpadł wyżej)
  if tg_op = 'UPDATE' and old.status = 'odwolana' then
    new.odwolal := null;
    new.odwolano := null;
    new.powod_odwolania := null;
  end if;

  czas_zmieniony := tg_op = 'INSERT'
    or new.poczatek <> old.poczatek
    or new.koniec <> old.koniec
    or new.rampa_id <> old.rampa_id
    or old.status <> 'aktywna';

  if not czas_zmieniony then
    return new;
  end if;

  if not exists (select 1 from public.rampy r where r.id = new.rampa_id and r.aktywna) then
    raise exception 'Ta rampa jest nieaktywna.';
  end if;

  -- dzień wolny: nikt nie wpisze awizacji (także biuro)
  if rola <> 'admin' and (new.poczatek at time zone u.strefa)::date = any (u.dni_wolne) then
    raise exception 'Ten dzień jest wolny – nie można wpisać awizacji.';
  end if;

  -- przerwa albo ręczna blokada okien: nikt nie wpisze awizacji (także biuro)
  if rola <> 'admin' then
    opis_bl := public.awz_kolizja_blokady(new.rampa_id, new.poczatek, new.koniec);
    if opis_bl is not null then
      raise exception '%', opis_bl;
    end if;
  end if;

  if rola = 'przewoznik' then
    lp := new.poczatek at time zone u.strefa;
    lk := new.koniec at time zone u.strefa;
    m0 := extract(hour from lp)::int * 60 + extract(minute from lp)::int;
    m1 := round(extract(epoch from (lk - date_trunc('day', lp))) / 60)::int;

    if new.poczatek < now() + make_interval(mins => u.min_wyprzedzenie) then
      raise exception 'Rezerwacja jest możliwa najpóźniej % min przed oknem.', u.min_wyprzedzenie;
    end if;
    if lp::date > (now() at time zone u.strefa)::date + u.dni_naprzod then
      raise exception 'Można rezerwować najwyżej % dni naprzód.', u.dni_naprzod;
    end if;
    if not (extract(isodow from lp)::int = any (u.dni_robocze)) or lp::date = any (u.dni_wolne) then
      raise exception 'Ten dzień jest wolny – rampa nie przyjmuje aut.';
    end if;
    if extract(second from lp) <> 0 or m0 < u.od_min or m1 > u.do_min then
      raise exception 'Rampa przyjmuje auta od % do %.', public.awz_hhmm(u.od_min), public.awz_hhmm(u.do_min);
    end if;
    if (m0 - u.od_min) % u.okno_min <> 0 or (m1 - m0) % u.okno_min <> 0 then
      raise exception 'Rezerwacja musi zaczynać się i kończyć na granicy okna (% min).', u.okno_min;
    end if;
    if (m1 - m0) > u.max_okien * u.okno_min then
      raise exception 'Jedna rezerwacja może trwać najwyżej % min.', u.max_okien * u.okno_min;
    end if;
  end if;

  return new;
end $$;

select 'blokady gotowe' as wynik, count(*) as ile from public.blokady;
